const mongoose = require("mongoose");

// A draft is separate from the live route: preparing a restaurant must not
// alter, activate, or replace an existing telephone installation.
const schema = new mongoose.Schema({
  restaurantId: { type: mongoose.Schema.Types.ObjectId, ref: "Restaurant", required: true, unique: true },
  wizardStep: { type: Number, min: 0, max: 6, default: 0 },
  accountSid: { type: String, sparse: true, unique: true },
  accountRequestedName: String,
  automation: {
    status: { type: String, enum: ["running", "waiting", "error", "completed"] },
    phase: String,
    message: String,
    maxAmount: String,
    currency: String,
    sharedCloneAccepted: { type: Boolean, default: false },
    functionAccepted: { type: Boolean, default: false },
    resumeMode: { type: String, enum: ["onboarding", "technical"] },
    actorId: String,
    nextAttemptAt: Date,
    manualApprovalBundleSid: String,
    manualApprovalAccountSid: String,
    runLeaseId: String,
    runLeaseUntil: Date,
  },
  bundleCloneOperation: { type: String, enum: ["not_started", "pending", "uncertain", "completed"], default: "not_started" },
  bundleCloneAttempt: { id: String, startedAt: Date },
  regulatoryApproval: { bundleSid: String, accountSid: String, status: String, compatible: Boolean, checkedAt: Date },
  regulatorySubmission: {
    state: { type: String, enum: ["running", "waiting", "uncertain", "submitted"] },
    attemptId: String, startedAt: Date, phase: String, fingerprint: String,
    regulationSid: String, endUserSid: String, documentSids: [String],
    bundleSid: String, assignedSids: [String], evaluationStatus: String,
  },
  regulatoryAddress: { state: { type: String, enum: ["pending", "uncertain", "completed"] }, attemptId: String, sid: String, fingerprint: String },
  regulatoryResubmission: { state: { type: String, enum: ["pending", "uncertain", "completed"] }, attemptId: String, bundleSid: String },
  bundleAssociation: { state: { type: String, enum: ["pending", "uncertain", "completed"] }, attemptId: String, bundleSid: String, numberSid: String },
  encryptedAuthToken: { type: String, select: false },
  accountOperation: { type: String, enum: ["not_started", "pending", "uncertain", "completed"], default: "not_started" },
  domainOperation: { type: String, enum: ["not_started", "pending", "uncertain", "completed"], default: "not_started" },
  domainFailure: { phase: String, status: Number, code: String, at: Date },
  sipDomain: String,
  sipDomainSid: { type: String, sparse: true, unique: true },
  phoneNumberSid: { type: String, sparse: true, unique: true },
  twilioNumber: { type: String, sparse: true, unique: true },
  numberOperation: { type: String, enum: ["not_started", "pending", "uncertain", "completed"], default: "not_started" },
  pendingNumber: String,
  lastNumberRejection: { phoneNumber: String, code: Number, status: Number, reason: String, at: Date },
  sipCredentialListSid: { type: String, sparse: true, unique: true },
  sipCredentialSid: String,
  sipUsername: String,
  encryptedSipPassword: { type: String, select: false },
  encryptedNextSipPassword: { type: String, select: false },
  sipSecretAvailable: { type: Boolean, default: false },
  sipResumeAuthorized: { type: Boolean, default: false },
  sipCredentialOperation: { type: String, enum: ["not_started", "pending", "uncertain", "completed"], default: "not_started" },
  webhookOperation: { type: String, enum: ["not_started", "pending", "uncertain", "completed"], default: "not_started" },
  testRouting: {
    state: { type: String, enum: ["pending", "active", "restoring", "restored", "uncertain"] },
    attemptId: String, numberSid: String, targetUrl: String,
    previous: { voiceUrl: String, voiceMethod: String, voiceFallbackUrl: String, voiceFallbackMethod: String },
  },
  fallbackDrill: {
    state: { type: String, enum: ["running", "restoring", "completed"] },
    scenario: { type: String, enum: ["http", "invalid", "timeout"] },
    expiresAt: Date, startedAt: Date, triggeredAt: Date, restoredAt: Date,
    results: { http: Boolean, invalid: Boolean, timeout: Boolean },
  },
  fallbackFunction: {
    operation: { type: String, enum: ["waiting", "pending", "uncertain", "completed"] },
    stage: String, attemptId: String, sipUri: String,
    serviceSid: String, functionSid: String, versionSid: String, buildSid: String,
    environmentSid: String, deploymentSid: String, domainName: String, url: String,
  },
  voiceFallbackUrl: String,
  verifiedFallbackUrl: { type: String, sparse: true, unique: true },
  fallbackProbeUrl: String,
  fallbackProbeSipUri: String,
  fallbackProbeAt: Date,
  serviceStatus: { type: String, enum: ["preparing", "compliance_pending", "hardware_pending", "ready_for_test", "active", "incident", "suspended"], default: "preparing" },
  activationOperation: { type: String, enum: ["idle", "pending"], default: "idle" },
  activationOperationId: String,
  operationAttempts: {
    account: { id: String, startedAt: Date },
    domain: { id: String, startedAt: Date, domainName: String },
    number: { id: String, startedAt: Date },
    sip: { id: String, startedAt: Date },
    webhook: { id: String, startedAt: Date },
    activation: { id: String, startedAt: Date },
  },
  recoveryInspection: {
    id: String,
    operation: String,
    state: String,
    attemptId: String,
    attemptStartedAt: Date,
    evidence: String,
    fingerprint: String,
    checkedAt: Date,
  },
  checklist: {
    terminalConnected: { type: Boolean, default: false },
    operatorForwarding: { type: Boolean, default: false },
    incomingTest: { type: Boolean, default: false },
    outgoingTest: { type: Boolean, default: false },
    callerIdTest: { type: Boolean, default: false },
    popupTest: { type: Boolean, default: false },
    pushTest: { type: Boolean, default: false },
    customerTest: { type: Boolean, default: false },
    emergencyTest: { type: Boolean, default: false },
    fallbackTest: { type: Boolean, default: false },
    fallbackNormalCall: { type: Boolean, default: false },
    fallbackBackendOutage: { type: Boolean, default: false },
    fallbackSipRinging: { type: Boolean, default: false },
    fallbackBidirectionalAudio: { type: Boolean, default: false },
    fallbackBackendRecovery: { type: Boolean, default: false },
    fallbackHttpFailures: { type: Boolean, default: false },
    missedTest: { type: Boolean, default: false },
  },
  terminalType: { type: String, enum: ["softphone", "HT813"], default: "softphone" },
  forwardingScenario: { type: String, enum: ["direct", "forward"] },
  regulatoryBundleSid: { type: String, default: "" },
  operator: { type: String, default: "", maxlength: 100 },
  audit: [{ action: String, actorId: String, at: Date, details: { type: String, maxlength: 500 } }],
}, { timestamps: true, bufferCommands: false });

module.exports = mongoose.model("CallSenseOnboarding", schema);
